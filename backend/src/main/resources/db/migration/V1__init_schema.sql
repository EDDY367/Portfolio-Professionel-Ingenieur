-- Schema du portfolio (PostgreSQL / Supabase). SQL volontairement portable (tests H2 en mode PostgreSQL).

CREATE TABLE admin_users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(200) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    active        BOOLEAN      DEFAULT TRUE NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE,
    CONSTRAINT admin_users_email_uk UNIQUE (email)
);

CREATE TABLE profiles (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name   VARCHAR(120)  NOT NULL,
    headline    VARCHAR(200)  NOT NULL,
    bio         VARCHAR(4000),
    email       VARCHAR(200),
    phone       VARCHAR(40),
    location    VARCHAR(120),
    photo_url   VARCHAR(500),
    cv_url      VARCHAR(500),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE
);

CREATE TABLE projects (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug           VARCHAR(120)   NOT NULL,
    title          VARCHAR(200)   NOT NULL,
    summary        VARCHAR(500),
    description    VARCHAR(10000),
    tech_stack     VARCHAR(500),
    github_url     VARCHAR(500),
    demo_url       VARCHAR(500),
    cover_image_url VARCHAR(500),
    is_featured    BOOLEAN        DEFAULT FALSE NOT NULL,
    is_published   BOOLEAN        DEFAULT TRUE  NOT NULL,
    display_order  INTEGER        DEFAULT 0     NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE,
    CONSTRAINT projects_slug_uk UNIQUE (slug)
);

CREATE TABLE skills (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    category      VARCHAR(60)  NOT NULL,
    level_pct     INTEGER      DEFAULT 70 NOT NULL,
    is_published  BOOLEAN      DEFAULT TRUE NOT NULL,
    display_order INTEGER      DEFAULT 0    NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE,
    CONSTRAINT skills_name_uk UNIQUE (name),
    CONSTRAINT skills_level_ck CHECK (level_pct BETWEEN 0 AND 100)
);

CREATE TABLE experiences (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_title    VARCHAR(200) NOT NULL,
    company       VARCHAR(200) NOT NULL,
    location      VARCHAR(120),
    start_date    DATE         NOT NULL,
    end_date      DATE,
    description   VARCHAR(5000),
    is_published  BOOLEAN      DEFAULT TRUE NOT NULL,
    display_order INTEGER      DEFAULT 0    NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE,
    CONSTRAINT experiences_dates_ck CHECK (end_date IS NULL OR end_date >= start_date)
);

CREATE TABLE educations (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    degree        VARCHAR(200) NOT NULL,
    school        VARCHAR(200) NOT NULL,
    start_year    INTEGER      NOT NULL,
    end_year      INTEGER,
    description   VARCHAR(2000),
    is_published  BOOLEAN      DEFAULT TRUE NOT NULL,
    display_order INTEGER      DEFAULT 0    NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE,
    CONSTRAINT educations_years_ck CHECK (end_year IS NULL OR end_year >= start_year)
);

CREATE TABLE certifications (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title          VARCHAR(200) NOT NULL,
    issuer         VARCHAR(200) NOT NULL,
    issued_on      DATE,
    credential_url VARCHAR(500),
    is_published   BOOLEAN      DEFAULT TRUE NOT NULL,
    display_order  INTEGER      DEFAULT 0    NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE
);

CREATE TABLE social_links (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    platform      VARCHAR(60)  NOT NULL,
    url           VARCHAR(500) NOT NULL,
    icon_key      VARCHAR(40),
    is_published  BOOLEAN      DEFAULT TRUE NOT NULL,
    display_order INTEGER      DEFAULT 0    NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE
);

CREATE TABLE messages (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_name  VARCHAR(120)  NOT NULL,
    sender_email VARCHAR(200)  NOT NULL,
    subject      VARCHAR(200),
    body         VARCHAR(4000) NOT NULL,
    is_read      BOOLEAN       DEFAULT FALSE NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP WITH TIME ZONE
);

CREATE INDEX projects_list_ix     ON projects (is_published, display_order);
CREATE INDEX skills_list_ix       ON skills (is_published, category, display_order);
CREATE INDEX experiences_list_ix  ON experiences (is_published, display_order);
CREATE INDEX messages_inbox_ix    ON messages (is_read, created_at);
